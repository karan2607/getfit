import { describe, it, expect } from 'vitest'
import contract from '../test/contract.json'
import type { MeasurementType } from './api'
import {
  ALL_SET_FIELDS, type SetField,
  fieldsFor, usesField, fieldLabel, toDisplayField, toStorageField,
  toDisplayWeight, toStorageWeight, timeUnitFor, distanceUnitFor,
  chartSpecFor, formatDuration,
} from './units'

/**
 * The server is the source of truth for the measurement-type contract; this
 * file mirrors it. That mirror DRIFTED and shipped a live bug: two types were
 * added server-side, an upgrade step reclassified 40 existing rows onto them,
 * and this union still listed five — so a treadmill fell back to `weight_reps`
 * and rendered weight and reps inputs whose values the server discarded.
 *
 * `src/test/contract.json` is generated by `manage.py export_set_contract`,
 * and CI runs it with `--check`, so the two cannot diverge silently again.
 */
describe('the contract matches the server', () => {
  it('knows every measurement type', () => {
    for (const type of contract.types) {
      expect(fieldsFor(type as MeasurementType),
        `no field contract for '${type}'`).toBeDefined()
      // The real failure was a MISS falling back to weight_reps, which looks
      // like a value. So compare against the server's list, not just defined.
      expect([...fieldsFor(type as MeasurementType)].sort())
        .toEqual([...(contract.field_contract as Record<string, string[]>)[type]].sort())
    }
  })

  it('knows every set field', () => {
    expect([...ALL_SET_FIELDS].sort()).toEqual([...contract.fields].sort())
  })

  it('matches the chart contract', () => {
    for (const type of contract.types) {
      const expected = (contract.chart_contract as Record<string, {
        metric: string | null; unit: string | null }>)[type]
      const actual = chartSpecFor(type as MeasurementType)
      expect(actual.metric).toBe(expected.metric)
      expect(actual.unit).toBe(expected.unit)
    }
  })

  it('does not render weight or reps for a cardio machine', () => {
    // The exact user-visible symptom of the drift.
    expect(usesField('cardio_machine', 'weight_kg')).toBe(false)
    expect(usesField('cardio_machine', 'reps_completed')).toBe(false)
    expect(usesField('cardio_machine', 'speed_kmh')).toBe(true)
    expect(usesField('cardio_machine', 'incline_pct')).toBe(true)
  })

  it('keeps duration on weight_distance', () => {
    // Load-bearing: each new contract is a superset of the one it replaced,
    // which is what made reclassifying existing rows lossless. Narrowing this
    // would retroactively null 17 logged carry and sled durations.
    expect(usesField('weight_distance', 'duration_seconds')).toBe(true)
    expect(usesField('weight_distance', 'weight_kg')).toBe(true)
    expect(usesField('weight_distance', 'distance_m')).toBe(true)
  })
})

describe('weight conversion', () => {
  it('round-trips through lb without drifting', () => {
    const kg = 60
    expect(toStorageWeight(toDisplayWeight(kg, 'lb'), 'lb')).toBeCloseTo(kg, 1)
  })

  it('passes kg through untouched', () => {
    expect(toDisplayWeight(60, 'kg')).toBe(60)
    expect(toStorageWeight(60, 'kg')).toBe(60)
  })

  it('treats null as absent, not zero', () => {
    expect(toDisplayWeight(null, 'lb')).toBeNull()
    expect(toStorageWeight(undefined, 'lb')).toBeNull()
  })
})

describe('timeUnitFor', () => {
  it('asks for minutes when the plan prescribes minutes', () => {
    // Reported: "the requested time should be in minutes and not secs" — a
    // 25-30 min treadmill walk was asking the user to type 1800.
    expect(timeUnitFor('25-30 min')).toBe('min')
    expect(timeUnitFor('10 minutes')).toBe('min')
  })

  it('asks for seconds for a hold', () => {
    expect(timeUnitFor('45 sec')).toBe('sec')
    expect(timeUnitFor('30s')).toBe('sec')
  })

  it('defaults to seconds when there is nothing to go on', () => {
    expect(timeUnitFor('')).toBe('sec')
    expect(timeUnitFor(null)).toBe('sec')
    expect(timeUnitFor('AMRAP')).toBe('sec')
  })
})

describe('distanceUnitFor', () => {
  it('takes the unit from the prescription', () => {
    // The whole reason weight_distance exists: "Farmer's Carry: 40 yards" was
    // an unenterable prescription for months.
    expect(distanceUnitFor('40 yards')).toBe('yd')
    expect(distanceUnitFor('30 yd')).toBe('yd')
    expect(distanceUnitFor('50 feet')).toBe('ft')
    expect(distanceUnitFor('100 m')).toBe('m')
  })

  it('defaults to metres, which is how it is stored', () => {
    expect(distanceUnitFor('')).toBe('m')
    expect(distanceUnitFor(null)).toBe('m')
  })
})

describe('field conversion', () => {
  it('shows minutes but stores seconds', () => {
    expect(toDisplayField('duration_seconds', 1800, 'lb', 'min')).toBe(30)
    expect(toStorageField('duration_seconds', 30, 'lb', 'min')).toBe(1800)
  })

  it('keeps 90 seconds as 1.5 minutes rather than a lossy 2', () => {
    expect(toDisplayField('duration_seconds', 90, 'lb', 'min')).toBe(1.5)
  })

  it('round-trips yards through metres', () => {
    const stored = toStorageField('distance_m', 40, 'lb', 'sec', 'yd')
    expect(toDisplayField('distance_m', stored, 'lb', 'sec', 'yd'))
      .toBeCloseTo(40, 1)
  })

  it('shows mph for lb users and km/h for kg users', () => {
    expect(toDisplayField('speed_kmh', 16.1, 'lb')).toBeCloseTo(10, 0)
    expect(toDisplayField('speed_kmh', 16.1, 'kg')).toBe(16.1)
  })

  it('does not round a fractional incline away', () => {
    // Rounding 3.5% to 4 defeats the point of recording it.
    expect(toStorageField('incline_pct', 3.5, 'lb')).toBe(3.5)
    expect(toStorageField('speed_kmh', 5.6, 'kg')).toBe(5.6)
  })

  it('floors negatives at zero', () => {
    expect(toStorageField('incline_pct', -2, 'lb')).toBe(0)
    expect(toStorageField('reps_completed', -5, 'lb')).toBe(0)
  })
})

describe('fieldLabel', () => {
  it('names the new fields with their unit', () => {
    expect(fieldLabel('speed_kmh', 'lb')).toBe('Speed (mph)')
    expect(fieldLabel('speed_kmh', 'kg')).toBe('Speed (km/h)')
    expect(fieldLabel('incline_pct', 'kg')).toBe('Incline (%)')
    expect(fieldLabel('distance_m', 'lb', '', 'sec', 'yd')).toBe('Distance (yd)')
  })

  it('says what you load, not just "weight"', () => {
    expect(fieldLabel('weight_kg', 'lb', 'Barbell Bench Press')).toBe('Bar (lb)')
    expect(fieldLabel('weight_kg', 'lb', 'Dumbbell Curl')).toBe('Each (lb)')
    expect(fieldLabel('weight_kg', 'kg', 'Cable Row')).toBe('Stack (kg)')
  })

  it('labels every field in the contract', () => {
    // A field with no label renders a blank column header.
    for (const field of ALL_SET_FIELDS) {
      expect(fieldLabel(field as SetField, 'lb').length,
        `no label for '${field}'`).toBeGreaterThan(0)
    }
  })
})

describe('formatDuration', () => {
  it('reads as time, not a raw count', () => {
    expect(formatDuration(90)).toContain('1')
    expect(formatDuration(45)).toContain('45')
  })

  it('handles absent values', () => {
    expect(formatDuration(null)).toBeTruthy()
  })
})
